class LoggedRandomSearch(RandomSearch):
    def __init__(self, problem, logger, image_name, output_dir, termination_criterion):
        super(LoggedRandomSearch, self).__init__(
            problem=problem,
            termination_criterion=termination_criterion
        )
        self.logger = logger
        self.image_name = image_name
        self.output_dir = output_dir
        self.best_fitness = -float("inf")
        self._initial_solution = None
        self._current_generation_start_time = None

    def evaluate(self, solution_list):
        evaluated = super(LoggedRandomSearch, self).evaluate(solution_list)
        self._initial_solution = evaluated[0]
        return evaluated

    def _log_solution(self, solution: FloatSolution, generation: int):
        selected_mmrs = solution.attributes['selected_mmrs_order']
        sampled_params = solution.attributes['sampled_mmr_params']
        original_result = solution.attributes['original_result']
        transformed_result = solution.attributes['transformed_result']

        overall_fitness = None
        obj1_attack_score = float(solution.attributes['obj1_attack_score'])
        obj2_distortion_score = float(solution.attributes['obj2_distortion_score'])

        self.logger.log({
            'Image_Name': self.image_name,
            'Generation': generation,
            'Selected_MMRs': selected_mmrs,
            'Active_Count': len(selected_mmrs),
            'Overall_Fitness': float("nan"),
            'Obj1_Attack_Score': obj1_attack_score,
            'Obj2_Distortion_Score': obj2_distortion_score,
            'MMR_Parameters': sampled_params,
            'Original_Caption': original_result['caption'],
            'Original_Categories': format_categories_string(original_result),
            'Transformed_Caption': transformed_result['caption'],
            'Transformed_Categories': format_categories_string(transformed_result),
        })

        status = "[Evaluated]"
        print(
            f"  Gen {generation}: "
            f"(Obj1: {obj1_attack_score:.4f}, Obj2: {obj2_distortion_score:.4f}, "
            f"Cnt: {len(selected_mmrs)}) {status}"
        )

    def init_progress(self) -> None:
        self.archive.add(self._initial_solution)
        self.evaluations = 1
        self._log_solution(self._initial_solution, generation=1)
        observable_data = self.observable_data()
        self.observable.notify_all(**observable_data)

    def step(self) -> None:
        self._current_generation_start_time = time.time()
        new_solution = self.problem.create_solution()
        self.problem.evaluate(new_solution)
        self.archive.add(new_solution)
        self._log_solution(new_solution, generation=self.evaluations + 1)
