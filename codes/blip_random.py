def _word_to_num(token: str):
    token = token.strip().lower()
    if token.isdigit():
        return int(token)
    return NUMBER_WORDS.get(token)

def _parse_count_from_chunk(chunk: str) -> int:
    chunk = chunk.lower().strip()

    m = re.search(r"\b(\d+)\b", chunk)
    if m:
        return int(m.group(1))

    for w, v in NUMBER_WORDS.items():
        if re.search(rf"\b{re.escape(w)}\b", chunk):
            return v

    if chunk and chunk not in {"none", "no", "nothing", "not visible", "not present"}:
        return 1
    return 0

def _count_items_in_text(text: str, vocab: set) -> int:
    text = text.lower()
    total = 0

    # split by commas / semicolons
    chunks = re.split(r"[;,]", text)
    for chunk in chunks:
        if any(re.search(rf"\b{re.escape(word)}\b", chunk) for word in vocab):
            total += _parse_count_from_chunk(chunk)

    # fallback: if category word exists but no count was found, count as 1
    if total == 0 and any(re.search(rf"\b{re.escape(word)}\b", text) for word in vocab):
        total = 1

    return total

def extract_category_counts(blip_output: str) -> dict:
    """
    Returns:
        {"Trash": int, "Objects": int, "Animal": int, "Vegetation": int}
    """
    text = blip_output.strip()
    lower = text.lower()

    counts = {"Trash": 0, "Objects": 0, "Animal": 0, "Vegetation": 0}

    line_map = {
        "animals:": ("Animal", ANIMAL_WORDS),
        "vegetation:": ("Vegetation", VEGETATION_WORDS),
        "trash:": ("Trash", TRASH_WORDS),
        "objects:": ("Objects", OBJECT_WORDS),
    }

    found_structured = False

    for prefix, (cat, vocab) in line_map.items():
        if prefix in lower:
            found_structured = True
            part = lower.split(prefix, 1)[1]
            part = part.split("\n", 1)[0].strip()
            if part not in {"none", "no", "nothing", "not visible", "not present"}:
                counts[cat] = _count_items_in_text(part, vocab)

    # fallback if model does not follow requested 4-line format
    #print("Fallback Structure Detected...!")
    if not found_structured:
        counts["Animal"] = _count_items_in_text(lower, ANIMAL_WORDS)
        counts["Vegetation"] = _count_items_in_text(lower, VEGETATION_WORDS)
        counts["Trash"] = _count_items_in_text(lower, TRASH_WORDS)
        counts["Objects"] = _count_items_in_text(lower, OBJECT_WORDS)

    return counts

