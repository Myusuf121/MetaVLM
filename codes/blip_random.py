# Keep the rest of the BLIP RandomSet pipeline unchanged.
# This only adds the outer run loop and preserves the existing CSV structure.
# ============================================================================

def run_random_set_search_jmetalpy(chat, image_dir, output_dir, max_eval=3000, n_runs=10):
    image_files = sorted([
        f for f in os.listdir(image_dir)
        if f.lower().endswith((".jpg", ".png", ".jpeg"))
    ])

    if not image_files:
        print("No images found in directory.")
        return []

    print(f"Found {len(image_files)} images. Starting BLIP jMetalPy Random Search for {n_runs} runs...")

    all_csv_paths = []

    for run_id in range(1, n_runs + 1):
        print("\n" + "=" * 80)
        print(f"BLIP RANDOMSET RUN {run_id}/{n_runs}")
        print("=" * 80)

        run_output_dir = os.path.join(output_dir, f"run_{run_id:02d}")
        os.makedirs(run_output_dir, exist_ok=True)

        logger = MMRLogger(run_output_dir)

        for idx, img_name in enumerate(image_files):
            print(f"\nProcessing Image {idx + 1}/{len(image_files)}: {img_name}")
            img_path = os.path.join(image_dir, img_name)

            try:
                # KEEP EXACT SAME PREDICTION VALIDATION CALL AS YOUR CURRENT BLIP RANDOMSET CODE
                _ = generate_marinegpt_prediction(Image.open(img_path).convert("RGB"), chat)
            except Exception as e:
                print(f"Skipping {img_name}: Error loading image - {e}")
                continue

            problem = JMetalRandomMMRProblem(
                image_path=img_path,
                chat=chat
            )

            algorithm = LoggedRandomSearch(
                problem=problem,
                logger=logger,
                image_name=img_name,
                output_dir=run_output_dir,
                termination_criterion=StoppingByEvaluations(
                    max_evaluations=max_eval
                )
            )

            algorithm.run()

            front = algorithm.result()
            pareto_csv_path = save_random_pareto_front(
                front=front,
                image_name=img_name,
                output_dir=run_output_dir
            )
            
            print(f"  Non-dominated Random Search Pareto solutions: {len(front)}")
            print(f"  Pareto front saved to: {pareto_csv_path}")


        csv_path = logger.get_csv_path()
        all_csv_paths.append(csv_path)
        print(f"\nRun {run_id} complete. Results saved to: {csv_path}")

    print(f"\nAll {n_runs} BLIP RandomSet runs complete.")
    return all_csv_paths

