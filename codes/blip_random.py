class JMetalRandomMMRProblem(FloatProblem):
    def number_of_objectives(self) -> int:
        return 2

    def number_of_constraints(self) -> int:
        return 0

    def number_of_variables(self) -> int:
        return 12

    def name(self) -> str:
        return "BLIP_RandomSearch"

    def __init__(self, image_path, chat=None):
        super(JMetalRandomMMRProblem, self).__init__()

        self.image_path = image_path
        self.chat = chat

        # Bounds are needed by FloatSolution; actual random generation is handled in create_solution()
        self.lower_bound = [
            0.0, -5.0,    # rotation flag, angle
            0.0, 0.7,     # scale flag, zoom_level
            0.0, 1.0,     # hist eq flag, clip_limit
            0.0, 0.9,     # downsample flag, scale_factor
            0.0, -0.15,   # shear flag, h_shear
            0.0, -0.03    # translate flag, h_shift_pct
        ]

        self.upper_bound = [
            1.0, 5.0,
            1.0, 1.3,
            1.0, 3.0,
            1.0, 1.0,
            1.0, 0.15,
            1.0, 0.03
        ]

    def create_solution(self) -> FloatSolution:
        solution = FloatSolution(
            lower_bound=self.lower_bound,
            upper_bound=self.upper_bound,
            number_of_objectives=self.number_of_objectives()
        )

        # Neutral defaults for inactive MMRs
        variables = [
            0.0, 0.0,        # rotation off
            0.0, 1.0,        # scale off
            0.0, 1.0,        # hist eq off
            0.0, 1.0,        # downsample off
            0.0, 0.0,        # shear off
            0.0, 0.0         # translate off
        ]

        # Same random-set logic: random active-count + random subset
        num_mmrs = random.randint(1, len(RANDOM_MMR_ORDER))
        selected_mmrs = random.sample(RANDOM_MMR_ORDER, num_mmrs)

        mmr_params = {}

        for mmr in selected_mmrs:
            params = generate_random_params(mmr)
            mmr_params[mmr] = params

            if mmr == 'MMR1_Rotation':
                variables[0] = 1.0
                variables[1] = params['angle']
            elif mmr == 'MMR2_Scale':
                variables[2] = 1.0
                variables[3] = params['zoom_level']
            elif mmr == 'MMR3_HistEq':
                variables[4] = 1.0
                variables[5] = params['clip_limit']
            elif mmr == 'MMR4_Downsample':
                variables[6] = 1.0
                variables[7] = params['scale_factor']
            elif mmr == 'MMR5_Shear':
                variables[8] = 1.0
                variables[9] = params['h_shear']
            elif mmr == 'MMR6_Translate':
                variables[10] = 1.0
                variables[11] = params['h_shift_pct']

        solution.variables = variables

        # Important: preserve exact order and full RGB weights
        solution.attributes['selected_mmrs_order'] = selected_mmrs
        solution.attributes['sampled_mmr_params'] = mmr_params

        return solution

    def evaluate(self, solution: FloatSolution) -> FloatSolution:
        selected_mmrs = solution.attributes.get('selected_mmrs_order', [])
        sampled_params = solution.attributes.get('sampled_mmr_params', {})

        original_image = Image.open(self.image_path).convert("RGB")
        original_result = generate_marinegpt_prediction(original_image, self.chat)

        transformed_img = Image.open(self.image_path).convert("RGB")
        for mmr in selected_mmrs:
            transformed_img = MMR_FUNCTIONS[mmr](transformed_img, **sampled_params[mmr])

        transformed_result = generate_marinegpt_prediction(transformed_img, self.chat)

        obj1_attack_score, obj2_distortion_score = calculate_fitness(
            original_result=original_result,
            transformed_result=transformed_result,
            selected_mmrs=selected_mmrs,
            current_params=sampled_params,
            total_mmrs=len(RANDOM_MMR_ORDER)
        )

        # jMetalPy minimizes objectives
        solution.objectives[0] = -1.0 * obj1_attack_score
        solution.objectives[1] = obj2_distortion_score

        solution.attributes['overall_fitness'] = None
        solution.attributes['obj1_attack_score'] = obj1_attack_score
        solution.attributes['obj2_distortion_score'] = obj2_distortion_score
        solution.attributes['original_result'] = original_result
        solution.attributes['transformed_result'] = transformed_result
        solution.attributes['transformed_image'] = transformed_img

        return solution


