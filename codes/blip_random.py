def calculate_fitness(original_result, transformed_result, selected_mmrs, current_params, total_mmrs=6.0):
    
    #original_result/transformed_result:{"caption": str, "categories": {"Trash": int, "Objects": int, "Animal": int, "Vegetation": int}}
    #selected_mmrs: list of active MMR names , current_params:dict of sampled params for active MMRs
    

    def get_param_magnitude_random(mmr_name, params):
        if mmr_name == 'MMR1_Rotation':
            return abs(params['angle']) / 5.0
        elif mmr_name == 'MMR2_Scale':
            return abs(params['zoom_level'] - 1.0) / 0.3
        elif mmr_name == 'MMR3_HistEq':
            return abs(params['clip_limit'] - 1.0) / 1.0
        elif mmr_name == 'MMR4_Downsample':
            return abs(params['scale_factor'] - 1.0) / 0.1
        elif mmr_name == 'MMR5_Shear':
            return abs(params['h_shear']) / 0.15
        elif mmr_name == 'MMR6_Translate':
            return abs(params['h_shift_pct']) / 0.03
        return 0.0

    # Obj1: same BLIP attack score based on count changes
    obj1_attack_score = 0.0
    for cat in cat_names:
        orig_count = original_result['categories'].get(cat, 0)
        final_count = transformed_result['categories'].get(cat, 0)
        diff = abs(orig_count - final_count)
        obj1_attack_score += diff / (diff + 1)

    # Obj2: same distortion score
    total_normalized_magnitude = 0.0
    for mmr in selected_mmrs:
        total_normalized_magnitude += get_param_magnitude_random(mmr, current_params[mmr])

    obj2_distortion_score = total_normalized_magnitude

    # Removed below line. It was supposed for 1+1 EA
    #overall_fitness = (0.5 * obj1_attack_score) + (0.5 * (1.0 - obj2_distortion_score))

    return obj1_attack_score, obj2_distortion_score


