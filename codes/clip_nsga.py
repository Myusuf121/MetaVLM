def generate_vlm_prediction(image, model, preprocess, device):
    """
    Multi-label classification with proper calibration.
    Returns: dict {category_name: confidence_score}
    """
    if isinstance(image, str):
        image = Image.open(image).convert("RGB")
    else:
        image = image.convert("RGB")

    image_input = preprocess(image).unsqueeze(0).to(device)

    with torch.no_grad():
        image_features = model.encode_image(image_input)
        image_features /= image_features.norm(dim=-1, keepdim=True)

        # Raw cosine similarities (range: -1 to 1, typically 0.15-0.35 for positives)
        logits = (image_features @ text_features_marine.T)[0].cpu().numpy()

    scores = logits
    # Convert to probabilities using sigmoid with temperature scaling
    # Temperature = 10.0 prevents saturation while maintaining discrimination
    #scores = 1 / (1 + np.exp(-10.0 * logits))

    results = {cat: float(score) for cat, score in zip(cat_names, scores)}
    return results

