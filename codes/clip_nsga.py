def rotate_image(image: Image.Image, angle: float) -> Image.Image:
    return image.rotate(angle, expand=False, fillcolor=(0, 0, 0))

def scale_image(image: Image.Image, zoom_level: float) -> Image.Image:
    width, height = image.size
    new_width = int(width * zoom_level)
    new_height = int(height * zoom_level)
    resized = image.resize((new_width, new_height), Image.Resampling.LANCZOS)
    if zoom_level > 1.0:
        left = (new_width - width) // 2
        top = (new_height - height) // 2
        return resized.crop((left, top, left + width, top + height))
    else:
        new_image = Image.new('RGB', (width, height), (0, 0, 0))
        paste_x = (width - new_width) // 2
        paste_y = (height - new_height) // 2
        new_image.paste(resized, (paste_x, paste_y))
        return new_image

def apply_histogram_equalization(image: Image.Image, clip_limit: float) -> Image.Image:
    img_array = np.array(image)
    lab = cv2.cvtColor(img_array, cv2.COLOR_RGB2LAB)
    l, a, b = cv2.split(lab)
    clahe = cv2.createCLAHE(clipLimit=clip_limit, tileGridSize=(16, 16))
    l_clahe = clahe.apply(l)
    lab_clahe = cv2.merge([l_clahe, a, b])
    img_clahe = cv2.cvtColor(lab_clahe, cv2.COLOR_LAB2RGB)
    return Image.fromarray(img_clahe)

def downsample_image(image: Image.Image, scale_factor: float) -> Image.Image:
    width, height = image.size
    intermediate_w = int(width * scale_factor)
    intermediate_h = int(height * scale_factor)
    downsampled = image.resize((intermediate_w, intermediate_h), Image.Resampling.NEAREST)
    return downsampled.resize((width, height), Image.Resampling.NEAREST)

def shear_image(image: Image.Image, h_shear: float) -> Image.Image:

    # Applies only horizontal shear to the image.
    # h_shear: Shear factor (e.g., 0.2 means x' = x + 0.2*y)

    img_array = np.array(image)
    height, width = img_array.shape[:2]

    # Shear matrix:
    # [1, h_shear, 0] -> x_new = x + h_shear * y
    # [0, 1,       0] -> y_new = y (No vertical change)
    shear_matrix = np.array([[1, h_shear, 0], [0, 1, 0]], dtype=np.float32)

    sheared = cv2.warpAffine(img_array, shear_matrix, (width, height), borderMode=cv2.BORDER_CONSTANT, borderValue=(0, 0, 0))
    return Image.fromarray(sheared)

def translate_image(image: Image.Image, h_shift_pct: float) -> Image.Image:

    # Applies only horizontal translation to the image.
    # h_shift_pct: Shift as a percentage of image width (e.g., 0.1 = 10% shift right)

    img_array = np.array(image)
    height, width = img_array.shape[:2]

    h_shift_px = int(width * h_shift_pct)

    # Translation matrix:
    # [1, 0, h_shift_px] -> x_new = x + h_shift_px
    # [0, 1, 0         ] -> y_new = y (No vertical change)
    translation_matrix = np.array([[1, 0, h_shift_px], [0, 1, 0]], dtype=np.float32)

    translated = cv2.warpAffine(img_array, translation_matrix, (width, height),borderMode=cv2.BORDER_CONSTANT, borderValue=(0, 0, 0))
    return Image.fromarray(translated)

