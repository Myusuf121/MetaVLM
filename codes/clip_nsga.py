class PopulationLogger:
    def __init__(self, output_dir):
        self.output_dir = output_dir
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        self.csv_filename = os.path.join(output_dir, f"nsgaii_population_results_{timestamp}.csv")

        self.headers = [
            'Image_Name',
            'Generation',
            'Generation_Time_Seconds',
            'Solution_ID',
            'Obj1_Attack_Score',
            'Obj2_Distortion_Score',
            'Active_MMRs',
            'MMR1_Rotation', 'MMR2_Scale', 'MMR3_HistEq', 'MMR4_Downsample','MMR5_Shear', 'MMR6_Translate',
            'Original_Confidence',
            'Transformed_Confidence'
        ]
        self._initialize_csv()

    def _initialize_csv(self):
        os.makedirs(self.output_dir, exist_ok=True)
        with open(self.csv_filename, 'w', newline='') as f:
            writer = csv.writer(f)
            writer.writerow(self.headers)

    def log_population(self, solutions, image_name, generation, generation_time_seconds):
        with open(self.csv_filename, 'a', newline='') as f:
            writer = csv.writer(f)

            for i, sol in enumerate(solutions):
                mmr_config = sol.attributes.get('mmr_config', {})
                fitness_details = sol.attributes.get('fitness_details', {})
                vlm_outputs = fitness_details.get('vlm_outputs', {})

                obj1_score = -1.0 * sol.objectives[0]
                obj2_score = sol.objectives[1]

                row = [
                    image_name,
                    generation,
                    f"{generation_time_seconds:.6f}",
                    i,
                    f"{obj1_score:.6f}",
                    f"{obj2_score:.6f}",
                    fitness_details.get('active_count', 0),
                    str(mmr_config.get('rotation', {}).get('enabled', False)),
                    str(mmr_config.get('scale', {}).get('enabled', False)),
                    str(mmr_config.get('histogram_eq', {}).get('enabled', False)),
                    str(mmr_config.get('downsample', {}).get('enabled', False)),
                    str(mmr_config.get('shear', {}).get('enabled', False)),
                    str(mmr_config.get('translate', {}).get('enabled', False)),
                    json.dumps(vlm_outputs.get('original', {})),
                    json.dumps(vlm_outputs.get('final', {}))
                ]
                writer.writerow(row)

    def get_csv_path(self):
        return self.csv_filename

class GenerationObserver(Observer):
    def __init__(self, logger, image_name):
        self.logger = logger
        self.image_name = image_name
        self.last_time = time.time()

    def update(self, *args, **kwargs):
        evaluations = kwargs.get("EVALUATIONS", 0)
        solutions = kwargs.get("SOLUTIONS", [])

        if not solutions:
            return

        current_time = time.time()
        generation_time_seconds = current_time - self.last_time
        self.last_time = current_time

        # NSGA-II uses population_size evaluations per generation after initialization
        # generation 0/1 handling is kept simple and consistent for logging
        self.logger.log_population(
            solutions=solutions,
            image_name=self.image_name,
            generation=evaluations,
            generation_time_seconds=generation_time_seconds
        )

