def main():
    IMAGE_DIR = "/global/D1/homes/user_name/venv/clip/input/"
    OUTPUT_DIR = "/global/D1/homes/user_name/venv/clip/output/"
    POPULATION_SIZE = 30
    MAX_EVALUATIONS = 3000
    N_RUNS = 10

    if not os.path.exists(IMAGE_DIR):
        print(f"Error: {IMAGE_DIR} does not exist.")
        return

    image_files = [
        str(f) for f in Path(IMAGE_DIR).glob("*")
        if f.suffix.lower() in [".jpg", ".png", ".jpeg"]
    ]
    image_files = sorted(image_files)

    if not image_files:
        print("No images found in directory.")
        return

    print(f"Found {len(image_files)} images. Starting NSGA-II for {N_RUNS} runs...")

    for run_id in range(1, N_RUNS + 1):
        print(f"\n{'=' * 80}")
        print(f"NSGA-II RUN {run_id}/{N_RUNS}")
        print(f"{'=' * 80}")

        run_output_dir = os.path.join(OUTPUT_DIR, f"run_{run_id:02d}")
        os.makedirs(run_output_dir, exist_ok=True)

        problem = MetamorphicTestingProblem(
            model=model_marine,
            preprocess=preprocess_marine,
            device=device,
            dataset_images=image_files,
            output_dir=OUTPUT_DIR
        )

        logger = PopulationLogger(run_output_dir)

        # >>> debugg this incase image_name is not stored instead of indexs
        for img_idx in range(len(image_files)):
            problem.current_image_index = img_idx
            problem.current_image_name = os.path.basename(image_files[img_idx])
            print(f"\nProcessing Image {img_idx + 1}/{len(image_files)}: {problem.current_image_name}")

            algorithm = NSGAII(
                problem=problem,
                population_size=POPULATION_SIZE,
                offspring_population_size=POPULATION_SIZE,
                mutation=PolynomialMutation(
                    probability=1.0 / problem.number_of_variables(),
                    distribution_index=10
                ),
                crossover=SBXCrossover(probability=0.9, distribution_index=15),
                selection=BinaryTournamentSelection(
                    comparator=RankingAndCrowdingDistanceComparator()
                ),
                termination_criterion=StoppingByEvaluations(
                    max_evaluations=MAX_EVALUATIONS
                )
            )
            #record each individual details
            generation_observer = GenerationObserver(logger=logger, image_name=problem.current_image_name)
            algorithm.observable.register(generation_observer)

            gen_start_time = time.time()
            algorithm.run()
            generation_time_seconds = time.time() - gen_start_time

            solutions = algorithm.result()
            print(f"  Optimization finished. Found {len(solutions)} solutions in Pareto Front.")
            print(f"  Generation time: {generation_time_seconds:.2f} seconds")

            # keep your existing CSV structure exactly as before
            #logger.log_pareto_front(solutions, img_idx, generation_time_seconds)

            best_attack = max(solutions, key=lambda s: -s.objectives[0])

            best_vars = problem._parse_solution(best_attack.variables)
            img_path = image_files[img_idx]
            current_img = Image.open(img_path).convert("RGB")

            if best_vars['rotation']['enabled']:
                current_img = rotate_image(current_img, best_vars['rotation']['angle'])
            if best_vars['scale']['enabled']:
                current_img = scale_image(current_img, best_vars['scale']['zoom_level'])
            if best_vars['histogram_eq']['enabled']:
                current_img = apply_histogram_equalization(
                    current_img, best_vars['histogram_eq']['clip_limit']
                )
            if best_vars['downsample']['enabled']:
                current_img = downsample_image(
                    current_img, best_vars['downsample']['scale_factor']
                )
            if best_vars['shear']['enabled']:
                p = best_vars['shear']
                current_img = shear_image(current_img, p['h_shear'])
            if best_vars['translate']['enabled']:
                p = best_vars['translate']
                current_img = translate_image(current_img, p['h_shift_pct'])

            save_path = os.path.join(
                run_output_dir, "pareto_images", f"img_{img_idx}_best_attack.png"
            )
            os.makedirs(os.path.dirname(save_path), exist_ok=True)
            current_img.save(save_path)
            print(f"  Best attack image saved to: {save_path}")

        print(f"\nRun {run_id} complete. Results at {logger.get_csv_path()}")

    print(f"\nAll {N_RUNS} NSGA-II runs complete.")

if __name__ == "__main__":
    main()

