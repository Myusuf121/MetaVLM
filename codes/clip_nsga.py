class MetamorphicTestingProblem(FloatProblem):
    def number_of_objectives(self) -> int: return 2
    def number_of_constraints(self) -> int: return 0
    def number_of_variables(self) -> int: return 12
    def name(self) -> str: return "NSGAII_MarineInsta"

    def __init__(self, model, preprocess, device, dataset_images, output_dir):
        super(MetamorphicTestingProblem, self).__init__()
        # Bounds for 6 MMRs (Flag, Param)
        self.lower_bound = [0.0, -5.0, 0.0, 0.7, 0.0, 1.0, 0.0, 0.9, 0.0, -0.15, 0.0, -0.03]
        self.upper_bound = [1.0, 5.0, 1.0, 1.3, 1.0, 2.0, 1.0, 1.0, 1.0, 0.15, 1.0, 0.03]

        self.model = model
        self.preprocess = preprocess
        self.device = device
        self.dataset_images = dataset_images
        self.output_dir = output_dir
        self.current_image_index = 0
        self.current_image_name = os.path.basename(self.dataset_images[0]) if self.dataset_images else None

    def evaluate(self, solution: FloatSolution) -> FloatSolution:
        variables = solution.variables
        mmr_config = self._parse_solution(variables)

        fitness_result = self._calculate_objectives(mmr_config)

        # NSGA-II Minimizes objectives by default
        # Objective 1: Attack Success (Maximize Conf Diff) -> Minimize (-Conf Diff)
        solution.objectives[0] = -1.0 * fitness_result['conf_diff_score']

        # Objective 2: Distortion (Minimize Magnitude) -> Minimize (Magnitude)
        solution.objectives[1] = fitness_result['avg_magnitude_total']

        # Store details for logging
        solution.attributes['fitness_details'] = fitness_result
        solution.attributes['mmr_config'] = mmr_config

        return solution

    def _parse_solution(self, variables):
        return {
            'rotation': {'enabled': variables[0] > 0.5, 'angle': variables[1]},
            'scale': {'enabled': variables[2] > 0.5, 'zoom_level': variables[3]},
            'histogram_eq': {'enabled': variables[4] > 0.5, 'clip_limit': variables[5]},
            'downsample': {'enabled': variables[6] > 0.5, 'scale_factor': variables[7]},
            'shear': {'enabled': variables[8] > 0.5, 'h_shear': variables[9], 'v_shear': 0.0},
            'translate': {'enabled': variables[10] > 0.5, 'h_shift_pct': variables[11], 'v_shift_pct': 0.0}
        }

    def _get_param_magnitude(self, mmr_name, params):
        if mmr_name == 'rotation': return abs(params['angle']) / 5.0
        elif mmr_name == 'scale': return abs(params['zoom_level'] - 1.0) / 0.3
        elif mmr_name == 'histogram_eq': return abs(params['clip_limit'] - 1.0) / 1.0
        elif mmr_name == 'downsample': return abs(params['scale_factor'] - 1.0) / 0.1
        elif mmr_name == 'shear': return abs(params['h_shear'])/0.15
        elif mmr_name == 'translate': return abs(params['h_shift_pct'])/0.03
        return 0.0

    def _calculate_objectives(self, mmr_config):
        image_path = self.dataset_images[self.current_image_index]

        # 1. Original Prediction
        original_confidences = generate_vlm_prediction(image_path, self.model, self.preprocess, self.device)

        # 2. Apply Transformations
        current_image = Image.open(image_path).convert("RGB")
        active_count = 0
        total_normalized_magnitude = 0.0
        total_mmrs = 6.0

        def apply_and_track(key, func_call):
            nonlocal active_count, total_normalized_magnitude, current_image
            current_image = func_call
            active_count += 1
            total_normalized_magnitude += self._get_param_magnitude(key, mmr_config[key])

        if mmr_config['rotation']['enabled']:
            apply_and_track('rotation', rotate_image(current_image, mmr_config['rotation']['angle']))
        if mmr_config['scale']['enabled']:
            apply_and_track('scale', scale_image(current_image, mmr_config['scale']['zoom_level']))
        if mmr_config['histogram_eq']['enabled']:
            apply_and_track('histogram_eq', apply_histogram_equalization(current_image, mmr_config['histogram_eq']['clip_limit']))
        if mmr_config['downsample']['enabled']:
            apply_and_track('downsample', downsample_image(current_image, mmr_config['downsample']['scale_factor']))
        if mmr_config['shear']['enabled']:
            p = mmr_config['shear']
            apply_and_track('shear', shear_image(current_image, p['h_shear']))
        if mmr_config['translate']['enabled']:
            p = mmr_config['translate']
            apply_and_track('translate', translate_image(current_image, p['h_shift_pct']))

        # If no MMRs, minimal distortion but no attack
        if active_count == 0:
            return {
                'conf_diff_score': 0.0,
                'avg_magnitude_total': 0.0,
                'active_count': 0,
                'vlm_outputs': {'original': original_confidences, 'final': original_confidences}
            }

        # 3. Final Prediction
        final_confidences = generate_vlm_prediction(current_image, self.model, self.preprocess, self.device)

        # 4. Calculate Scores
        # Obj 1: Confidence Difference (0.0 to 1.0)
        diff_sum = sum(abs(original_confidences.get(cat, 0) - final_confidences.get(cat, 0)) for cat in cat_names)
        avg_conf_diff = diff_sum

        # Obj 2: Distortion (Average Magnitude over TOTAL MMRs) (0.0 to 1.0)
        avg_magnitude_total = total_normalized_magnitude

        return {
            'conf_diff_score': avg_conf_diff,
            'avg_magnitude_total': avg_magnitude_total,
            'active_count': active_count,
            'vlm_outputs': {'original': original_confidences, 'final': final_confidences}
        }

