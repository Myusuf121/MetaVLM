def generate_random_params(mmr_name):
    if mmr_name == 'MMR1_Rotation':
        return {'angle': random.uniform(-5.0, 5.0)}
    elif mmr_name == 'MMR2_Scale':
        return {'zoom_level': random.uniform(0.7, 1.3)}
    elif mmr_name == 'MMR3_HistEq':
        return {'clip_limit': random.uniform(1.0, 3.0)}
    elif mmr_name == 'MMR4_Downsample':
        return {'scale_factor': random.uniform(0.9, 1.0)}
    elif mmr_name == 'MMR5_Shear':
        return {'h_shear': random.uniform(-0.15, 0.15)}
    elif mmr_name == 'MMR6_Translate':
        return {'h_shift_pct': random.uniform(-0.03, 0.03)}
    return {}


def get_param_magnitude(mmr_name, params):
    """
    Same distortion logic already used in the notebook's Random Search.
    """
    if mmr_name == 'rotation':
        return abs(params.get('angle', 0.0) - 0.0) / 5.0
    elif mmr_name == 'scale':
        return abs(params.get('zoom_level', 1.0) - 1.0) / 0.3
    elif mmr_name == 'histogram_eq':
        return abs(params.get('clip_limit', 1.0) - 1.0) / 1.0
    elif mmr_name == 'downsample':
        return abs(params.get('scale_factor', 1.0) - 1.0) / 0.1
    elif mmr_name == 'shear':
        return abs(params.get('h_shear', 0.0)) / 0.15
    elif mmr_name == 'translate':
        return abs(params.get('h_shift_pct', 0.0)) / 0.03
    return 0.0


def calculate_fitness(original_conf, transformed_conf, active_count, total_mmrs=6, mmr_params=None, selected_mmrs=None):
    """
    Same fitness definition already used in the notebook's Random Search.
    Obj1 = attack score
    Obj2 = distortion score
    Overall = 0.5 * Obj1 + 0.5 * (1 - Obj2)
    """
    if mmr_params is None:
        mmr_params = {}
    if selected_mmrs is None:
        selected_mmrs = []

    obj1_attack_score = 0.0
    for cat in cat_names:
        orig_conf = float(original_conf.get(cat, 0.0))
        trans_conf = float(transformed_conf.get(cat, 0.0))
        obj1_attack_score += abs(orig_conf - trans_conf)

    #obj1_attack_score = obj1_attack_score / 2.0

    total_normalized_magnitude = 0.0
    random_to_nsga_name = {
        'MMR1_Rotation': 'rotation',
        'MMR2_Scale': 'scale',
        'MMR3_HistEq': 'histogram_eq',
        'MMR4_Downsample': 'downsample',
        'MMR5_Shear': 'shear',
        'MMR6_Translate': 'translate'
    }

    for mmr in selected_mmrs:
        nsga_name = random_to_nsga_name[mmr]
        total_normalized_magnitude += get_param_magnitude(nsga_name, mmr_params[mmr])

    obj2_distortion_score = total_normalized_magnitude
    #overall_fitness = (0.5 * obj1_attack_score) + (0.5 * (1.0 - obj2_distortion_score))

    return obj1_attack_score, obj2_distortion_score


