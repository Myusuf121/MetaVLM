# jMetalPy PROBLEM FOR RANDOM SEARCH
# Key point:
# - Uses jMetalPy FloatSolution so later HV/IGD can be computed in jMetalPy.
# - Preserves the ORIGINAL random MR generation logic by overriding create_solution().
# - Keeps the original random choice of:
#     * number of selected MMRs
#     * subset of selected MMRs
#     * sequential application order
#     * parameter sampling ranges
# ============================================================================

class JMetalRandomMMRProblem(FloatProblem):
    def number_of_objectives(self) -> int:
        return 2

    def number_of_constraints(self) -> int:
        return 0

    def number_of_variables(self) -> int:
        return 12

    def name(self) -> str:
        return "RandomSearch_MarineInsta"

    def __init__(self, model, preprocess, device, image_path):
        super(JMetalRandomMMRProblem, self).__init__()

        # Bounds are only used to build a valid FloatSolution.
        # They are set to cover the ORIGINAL random-search parameter ranges.
        self.lower_bound = [
            0.0, -5.0,   # flag, rotation angle
            0.0, 0.7,    # flag, scale
            0.0, 1.0,    # flag, hist eq
            0.0, 0.9,    # flag, downsample
            0.0, -0.15,  # flag, shear
            0.0, -0.03   # flag, translate
        ]
        self.upper_bound = [
            1.0, 5.0,
            1.0, 1.3,
            1.0, 2.0,
            1.0, 1.0,
            1.0, 0.15,
            1.0, 0.03
        ]

        self.model = model
        self.preprocess = preprocess
        self.device = device
        self.image_path = image_path

    def create_solution(self) -> FloatSolution:
        """
        This is the critical replacement:
        instead of ad hoc notebook sampling outside jMetalPy,
        we let the jMetalPy problem generate solutions that exactly follow
        the original Random Search sampling logic.
        """
        solution = FloatSolution(
            lower_bound=self.lower_bound,
            upper_bound=self.upper_bound,
            number_of_objectives=self.number_of_objectives()
        )

        # Neutral defaults for inactive MMRs
        variables = [
            0.0, 0.0,   # rotation off, angle neutral
            0.0, 1.0,   # scale off, neutral
            0.0, 1.0,   # hist eq off, neutral
            0.0, 1.0,   # downsample off, neutral
            0.0, 0.0,   # shear off, neutral
            0.0, 0.0    # translate off, neutral
        ]

        # Original logic: choose a random set size from 1..7, then random subset
        num_mmrs = random.randint(1, len(RANDOM_MMR_ORDER))
        selected_mmrs = random.sample(RANDOM_MMR_ORDER, num_mmrs)

        mmr_params = {}

        for mmr in selected_mmrs:
            params = generate_random_params(mmr)
            mmr_params[mmr] = params

            if mmr == 'MMR1_Rotation':
                variables[0] = 1.0
                variables[1] = params['angle']
            elif mmr == 'MMR2_Scale':
                variables[2] = 1.0
                variables[3] = params['zoom_level']
            elif mmr == 'MMR3_HistEq':
                variables[4] = 1.0
                variables[5] = params['clip_limit']
            elif mmr == 'MMR4_Downsample':
                variables[6] = 1.0
                variables[7] = params['scale_factor']
            elif mmr == 'MMR5_Shear':
                variables[8] = 1.0
                variables[9] = params['h_shear']
            elif mmr == 'MMR6_Translate':
                variables[10] = 1.0
                variables[11] = params['h_shift_pct']

        solution.variables = variables

        # Preserve information that cannot be reconstructed from the 14-D vector:
        # 1) random MMR order, because transformations are sequential and order matters
        # 2) exact RGB weights, because only one placeholder variable is stored in the vector
        solution.attributes['selected_mmrs_order'] = selected_mmrs
        solution.attributes['sampled_mmr_params'] = mmr_params

        return solution

    def evaluate(self, solution: FloatSolution) -> FloatSolution:
        selected_mmrs = solution.attributes.get('selected_mmrs_order', [])
        sampled_params = solution.attributes.get('sampled_mmr_params', {})

        original_conf = generate_vlm_prediction(
            self.image_path, self.model, self.preprocess, self.device
        )

        transformed_img = Image.open(self.image_path).convert("RGB")

        for mmr in selected_mmrs:
            params = sampled_params[mmr]
            transformed_img = MMR_FUNCTIONS[mmr](transformed_img, **params)

        transformed_conf = generate_vlm_prediction(
            transformed_img, self.model, self.preprocess, self.device
        )

        obj1_attack_score, obj2_distortion_score = calculate_fitness(
            original_conf=original_conf,
            transformed_conf=transformed_conf,
            active_count=len(selected_mmrs),
            total_mmrs=len(RANDOM_MMR_ORDER),
            mmr_params=sampled_params,
            selected_mmrs=selected_mmrs
        )

        # jMetalPy assumes minimization.
        # To maximize attack score fairly, store -Obj1 internally, exactly as done in NSGA-II.
        solution.objectives[0] = -1.0 * obj1_attack_score
        solution.objectives[1] = obj2_distortion_score

        # Keep raw outputs for logging / downstream analysis compatibility
        solution.attributes['overall_fitness'] = None
        solution.attributes['obj1_attack_score'] = obj1_attack_score
        solution.attributes['obj2_distortion_score'] = obj2_distortion_score
        solution.attributes['original_confidence'] = original_conf
        solution.attributes['transformed_confidence'] = transformed_conf
        solution.attributes['transformed_image'] = transformed_img

        return solution


