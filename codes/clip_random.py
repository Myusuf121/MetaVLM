class LoggedRandomSearch(RandomSearch):
    def __init__(self, problem, logger, image_name, output_dir, termination_criterion):
        super(LoggedRandomSearch, self).__init__(
            problem=problem,
            termination_criterion=termination_criterion
        )
        self.logger = logger
        self.image_name = image_name
        self.output_dir = output_dir
        self.best_fitness = -float("inf")
        self._initial_solution = None
        self._current_generation_start_time = None

    def evaluate(self, solution_list):
        evaluated = super(LoggedRandomSearch, self).evaluate(solution_list)
        self._initial_solution = evaluated[0]
        return evaluated

    def _log_solution(self, solution: FloatSolution, generation: int, generation_time_seconds: float):
        selected_mmrs = solution.attributes.get('selected_mmrs_order', [])
        mmr_params = solution.attributes.get('sampled_mmr_params', {})
        overall_fitness = None

        self.logger.log({
            'Image_Name': self.image_name,
            'Generation': generation,
            'Generation_Time_Seconds': generation_time_seconds,
            'Selected_MMRs': selected_mmrs,
            'Active_Count': len(selected_mmrs),
            'Overall_Fitness': float("nan"),
            'Obj1_Attack_Score': float(solution.attributes['obj1_attack_score']),
            'Obj2_Distortion_Score': float(solution.attributes['obj2_distortion_score']),
            'MMR_Parameters': mmr_params,
            'Original_Confidence': solution.attributes['original_confidence'],
            'Transformed_Confidence': solution.attributes['transformed_confidence']
        })

        save_path = os.path.join(
            self.output_dir,
            "transformed_images",
            f"{Path(self.image_name).stem}_gen{generation}.png"
        )

        status = "[EVALUATED]"
        os.makedirs(os.path.dirname(save_path), exist_ok=True)
        solution.attributes['transformed_image'].save(save_path)
        print(
            f"  Gen {generation}: "
            f"(Obj1: {solution.attributes['obj1_attack_score']:.4f}, "
            f"Obj2: {solution.attributes['obj2_distortion_score']:.4f}, "
            f"Time: {generation_time_seconds:.2f}s, "
            f"Cnt: {len(selected_mmrs)}) {status}"
        )

    def init_progress(self) -> None:
        self.archive.add(self._initial_solution)
        self.evaluations = 1
        self._log_solution(
            solution=self._initial_solution,
            generation=1,
            generation_time_seconds=0.0
        )
        observable_data = self.observable_data()
        self.observable.notify_all(**observable_data)

    def step(self) -> None:
        self._current_generation_start_time = time.time()
        new_solution = self.problem.create_solution()
        self.problem.evaluate(new_solution)
        self.archive.add(new_solution)

        generation_time_seconds = time.time() - self._current_generation_start_time
        self._log_solution(
            solution=new_solution,
            generation=self.evaluations + 1,
            generation_time_seconds=generation_time_seconds
        )

