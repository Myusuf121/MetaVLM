class GenerationObserver(Observer):
    def __init__(self, logger, image_name, population_size):
        self.logger = logger
        self.image_name = image_name
        self.population_size = population_size
        self.last_time = time.time()

    def update(self, *args, **kwargs):
        evaluations = kwargs.get("EVALUATIONS", 0)
        solutions = kwargs.get("SOLUTIONS", [])

        if not solutions:
            return

        current_time = time.time()
        generation_time_seconds = current_time - self.last_time
        self.last_time = current_time

        generation = max(1, int(np.ceil(evaluations / self.population_size)))

        self.logger.log_population(
            solutions=solutions,
            image_name=self.image_name,
            generation=generation,
            generation_time_seconds=generation_time_seconds
        )

