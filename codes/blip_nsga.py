    def _calculate_objectives(self, mmr_config):
        image_path = self.dataset_images[self.current_image_index]

        # 1. Original Prediction
        original_confidences = generate_marinegpt_prediction(Image.open(image_path).convert("RGB"))

        #print(f"VLM Output Original Image: Caption : {original_confidences['caption']}")
        #print(f"VLM Output Original Image: Counts  :   {original_confidences['categories']}")


