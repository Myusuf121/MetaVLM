class MetamorphicTestingProblem(FloatProblem):
    def number_of_objectives(self) -> int: return 2
    def number_of_constraints(self) -> int: return 0
    def number_of_variables(self) -> int: return 12
    def name(self) -> str: return "NSGAII_marineGPT"

    def __init__(self, dataset_images, output_dir):
        super(MetamorphicTestingProblem, self).__init__()
        # Bounds for 6 MMRs (Flag, Param)
        self.lower_bound = [0.0, -5.0, 0.0, 0.7, 0.0, 1.0, 0.0, 0.9, 0.0, -0.15, 0.0, -0.03]
        self.upper_bound = [1.0,  5.0, 1.0, 1.3, 1.0, 2.0, 1.0, 1.0, 1.0, 0.15, 1.0, 0.03]

        self.dataset_images = dataset_images
        self.output_dir = output_dir
        self.current_image_index = 0
        self.current_image_name = os.path.basename(self.dataset_images[0]) if self.dataset_images else None

    def evaluate(self, solution: FloatSolution) -> FloatSolution:
        variables = solution.variables
        mmr_config = self._parse_solution(variables)

        fitness_result = self._calculate_objectives(mmr_config)

        # NSGA-II Minimizes objectives by default
        # Objective 1: Attack Success (Maximize Conf Diff) -> Minimize (-Conf Diff)
        solution.objectives[0] = -1.0 * fitness_result['conf_diff_score']

        # Objective 2: Distortion (Minimize Magnitude) -> Minimize (Magnitude)
        solution.objectives[1] = fitness_result['avg_magnitude_total']

        # Store details for logging
        solution.attributes['fitness_details'] = fitness_result
        solution.attributes['mmr_config'] = mmr_config

        return solution

    def _parse_solution(self, variables):
        return {
            'rotation': {'enabled': variables[0] > 0.5, 'angle': variables[1]},
            'scale': {'enabled': variables[2] > 0.5, 'zoom_level': variables[3]},
            'histogram_eq': {'enabled': variables[4] > 0.5, 'clip_limit': variables[5]},
            'downsample': {'enabled': variables[6] > 0.5, 'scale_factor': variables[7]},
            'shear': {'enabled': variables[8] > 0.5, 'h_shear': variables[9], 'v_shear': 0.0},
            'translate': {'enabled': variables[10] > 0.5, 'h_shift_pct': variables[11], 'v_shift_pct': 0.0}
        }


