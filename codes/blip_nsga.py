            print(f"\nProcessing Image {img_idx + 1}/{len(image_files)}: {problem.current_image_name}")

            algorithm = NSGAII(
                problem=problem,
                population_size=POPULATION_SIZE,
                offspring_population_size=POPULATION_SIZE,
                mutation=PolynomialMutation(
                    probability=1.0 / problem.number_of_variables(),
                    distribution_index=10
                ),
                crossover=SBXCrossover(probability=0.9, distribution_index=15),
                selection=BinaryTournamentSelection(
                    comparator=RankingAndCrowdingDistanceComparator()
                ),
                termination_criterion=StoppingByEvaluations(
                    max_evaluations=MAX_EVALUATIONS
                )
            )
            generation_observer = GenerationObserver(
            logger=logger, image_name=problem.current_image_name, population_size=POPULATION_SIZE)
            algorithm.observable.register(generation_observer)

            gen_start_time = time.time()
            algorithm.run()
            generation_time_seconds = time.time() - gen_start_time

            solutions = algorithm.result()
            print(f"  Optimization finished. Found {len(solutions)} solutions in Pareto Front.")
            print(f"  Generation time: {generation_time_seconds:.2f} seconds")

