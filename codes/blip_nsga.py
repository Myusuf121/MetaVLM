def generate_blip_prediction(image, question=CATEGORY_PROMPT, max_new_tokens=80):
    if isinstance(image, str):
        image = Image.open(image).convert("RGB")
    else:
        image = image.convert("RGB")

    if device.type == "cuda":
        inputs = processor(images=image, text=question, return_tensors="pt").to(device, torch.float16)
    else:
        inputs = processor(images=image, text=question, return_tensors="pt").to(device)

    with torch.no_grad():
        outputs = model.generate(
            **inputs,
            max_new_tokens=max_new_tokens,
            do_sample=False
        )

    generated_text = processor.batch_decode(outputs, skip_special_tokens=True)[0].strip()

    if generated_text.lower().startswith(question.lower()):
        generated_text = generated_text[len(question):].strip(": ").strip()

    category_counts = extract_category_counts(generated_text)

    return {
        "caption": generated_text,
        "categories": category_counts
    }

def generate_marinegpt_prediction(image, chat=None):
    return generate_blip_prediction(image)

